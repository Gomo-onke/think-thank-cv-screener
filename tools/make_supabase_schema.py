"""Write supabase/schema.sql - the file you paste into the Supabase SQL editor.

    python tools/make_supabase_schema.py

It is generated from database.py (the single source of truth), so the online database always matches the code.
Run it again after changing the tables; a test fails if the committed file is out of date.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import database as db  # noqa: E402
import pgcompat  # noqa: E402

HEADER = """-- Think Tank recruitment portal - database for Supabase (Postgres).
-- Paste this whole file into Supabase > SQL Editor > New query > Run. It is safe to run more than once.
-- GENERATED by tools/make_supabase_schema.py from database.py - do not edit by hand.
--
-- Security: Row Level Security is ON for every table and there are NO policies, and the public API roles
-- (anon, authenticated) have no privileges. So the Supabase REST API / anon key can read or write nothing.
-- Only the portal server, which connects with the database password (DATABASE_URL), can use these tables.

"""

if __name__ == "__main__":
    out = os.path.join(ROOT, "supabase", "schema.sql")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEADER + db.pg_schema(with_revoke=True) + "\n\n" + pgcompat.REST_SETUP_SQL)
    print("wrote", out)
